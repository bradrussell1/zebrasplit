// Build the App Store Connect / Play in-app purchase sheet from the generated
// wardrobe, so the product IDs can never drift from the catalogue the app ships.
//
// Apple's limits are tight and silently truncate in the UI: display name 30
// characters, description 45. Both are asserted here rather than discovered
// after pasting every row by hand. Product IDs are permanent once created - they
// cannot be deleted or reused on the account - and they need not match the
// bundle id, which is stuck on com.bunktab.app forever. Users never see these,
// but we read them in sales reports for years, so they carry the current brand.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const SRC = "packages/core/src/outfits.generated.ts";
const PREFIX = "com.zebrasplit";
const NAME_MAX = 30, DESC_MAX = 45;

const src = readFileSync(SRC, "utf8");

// Only `paid` items get a product of their own. A `pack` item - the tiara - is
// sold inside a pack and has no store product, which is the point of it.
const items = [...src.matchAll(/\{ id: "([^"]+)", name: "([^"]+)", slot: "([^"]+)".*?status: "paid", price: "([^"]+)".*?\}/g)]
  .map(([, id, name, slot, price]) => ({ id, name, slot, price, kind: "cosmetic" }));

const packs = [...src.matchAll(/\{ id: "([^"]+)", name: "([^"]+)", price: "([^"]+)", items: \[([^\]]*)\]/g)]
  .map(([, id, name, price, list]) => ({
    id, name, price, kind: "pack",
    items: list.split(",").map((s) => s.trim().replace(/"/g, "")).filter(Boolean),
  }));

// Pack copy is written per pack; cosmetics follow one pattern that stays inside
// the 45-character limit for every name in the catalogue.
const PACK_DESC = {
  bachelorette: "Sash, skirt and tiara for the bride's zebra.",
  jersey: "All four jerseys: blue, green, purple, red.",
  hat: "All four caps: blue, green, purple and red.",
};

const SLOT_LABEL = { head: "Head", faceneck: "Face and neck", body: "Body" };

const rows = [
  ...items.map((it) => ({
    type: "Non-Consumable",
    reference: `Cosmetic - ${it.name}`,
    productId: `${PREFIX}.cosmetic.${it.id}`,
    display: it.name,
    description: `${it.name} for your zebra, kept for good.`,
    price: it.price,
    slot: SLOT_LABEL[it.slot] ?? it.slot,
    grants: it.id,
  })),
  ...packs.map((p) => ({
    type: "Non-Consumable",
    reference: `Pack - ${p.name}`,
    productId: `${PREFIX}.pack.${p.id}`,
    display: p.name,
    description: PACK_DESC[p.id],
    price: p.price,
    slot: "Pack",
    grants: p.items.join(" + "),
  })),
];

const problems = [];
for (const r of rows) {
  if (!r.description) { problems.push(`no description written for ${r.productId}`); continue; }
  if (r.display.length > NAME_MAX) problems.push(`display ${r.display.length}>${NAME_MAX}: ${r.display}`);
  if (r.description.length > DESC_MAX) problems.push(`description ${r.description.length}>${DESC_MAX}: ${r.description}`);
}
const ids = rows.map((r) => r.productId);
const dupes = ids.filter((v, i) => ids.indexOf(v) !== i);
if (dupes.length) problems.push(`duplicate product ids: ${[...new Set(dupes)].join(", ")}`);
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }

mkdirSync("docs/ops", { recursive: true });

const esc = (s) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
const csv = [
  "Type,Reference Name,Product ID,Display Name,Description,Price (USD),Slot,Grants",
  ...rows.map((r) => [r.type, r.reference, r.productId, r.display, r.description, r.price, r.slot, r.grants].map(esc).join(",")),
].join("\n");
writeFileSync("docs/ops/iap-products.csv", csv + "\n");

const md = [
  "# In-app purchase products",
  "",
  "Generated by `scripts/make-iap-sheet.mjs` from `packages/core/src/outfits.generated.ts`.",
  "Re-run it after changing the wardrobe; do not edit this file by hand.",
  "`docs/ops/iap-products.csv` is the same table, for pasting into a spreadsheet.",
  "",
  "## Before you start",
  "",
  "- **Product IDs are permanent.** Apple and Google never release one for reuse, even",
  "  after deletion, so these strings outlive almost everything else here.",
  "- **The prefix is the brand, not the bundle id.** Matching the bundle is convention,",
  "  not a requirement. `com.bunktab.app` is frozen for the life of the app; these are",
  "  not, and they show up in sales and revenue reports we read for years.",
  `- **All ${rows.length} are Non-Consumable.** An outfit is a permanent unlock, not a currency.`,
  "- **The first purchase ships with a version.** App Store Connect requires the first",
  "  in-app purchase to be submitted alongside a new app version, so these go to review",
  "  attached to 1.1.0 rather than on their own.",
  "- **Every product needs a review screenshot** (Apple, 640x920 or larger). The Shop",
  "  screen showing the item is enough, and one screenshot may be reused across items.",
  "- **Restore Purchases is mandatory.** Apple rejects non-consumables without it.",
  "",
  "## Play differences",
  "",
  "Play calls these one-time products and takes no review screenshot. The product id,",
  "display name and description map across unchanged; Play's description limit is 200",
  "characters rather than 45, so the text below fits with room to spare.",
  "",
  "## The products",
  "",
  "| # | Type | Reference Name | Product ID | Display Name | Description | USD |",
  "|--:|---|---|---|---|---|--:|",
  ...rows.map((r, i) => `| ${i + 1} | ${r.type} | ${r.reference} | \`${r.productId}\` | ${r.display} | ${r.description} | $${r.price} |`),
].join("\n");
writeFileSync("docs/ops/iap-products.md", md + "\n");

const n99 = rows.filter((r) => r.price === "0.99").length;
const n299 = rows.filter((r) => r.price === "2.99").length;
console.log(`${rows.length} products: ${n99} at $0.99, ${n299} at $2.99`);
console.log(`longest display ${Math.max(...rows.map((r) => r.display.length))}/${NAME_MAX}, longest description ${Math.max(...rows.map((r) => r.description.length))}/${DESC_MAX}`);
console.log("wrote docs/ops/iap-products.csv and docs/ops/iap-products.md");
